// Usage: node scripts/arrange-remaining-images.mjs [--start 87] [--end 307]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const ORDER = [
  "home.json",
  "core-services.json",
  "strategies.json",
  "industries.json",
  "b2b-b2c.json",
  "capture-qualification.json",
  "tools-compare.json",
  "resources.json",
];
const entries = ORDER.flatMap((f) => JSON.parse(readFileSync(`docs/image-prompts/${f}`, "utf8")));

const args = process.argv.slice(2);
function getArg(flag, def) {
  const idx = args.indexOf(flag);
  return idx !== -1 && args[idx + 1] ? parseInt(args[idx + 1], 10) : def;
}

const START = Math.max(87, getArg("--start", 87));
const END = Math.min(307, getArg("--end", 307));

const INCOMING = "public/images/incoming";
mkdirSync(`${INCOMING}/done`, { recursive: true });
mkdirSync("public/images/pages", { recursive: true });

const usedPhotoIds = new Set();

function cleanScene(scene) {
  return scene
    .replace(/,\s*[A-Z][a-zA-Z\s]+$/, "") // remove trailing city like ", Bhopal"
    .replace(/\b(a|an|the|in|at|on|with|and|of|for|to|by|into|over|across)\b/gi, " ")
    .replace(/[^a-zA-Z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

async function searchUnsplash(query) {
  try {
    const url = `https://unsplash.com/napi/search/photos?query=${encodeURIComponent(query)}&per_page=12`;
    const res = await fetch(url, { signal: AbortSignal.timeout(8000) });
    if (!res.ok) return [];
    const data = await res.json();
    return data.results || [];
  } catch {
    return [];
  }
}

function isPhotoGood(p) {
  if (!p || !p.id || usedPhotoIds.has(p.id)) return false;
  const desc = `${p.alt_description || ""} ${p.description || ""}`.toLowerCase();
  const bad = ["illustration", "cartoon", "3d render", "vector", "drawing", "render", "cgi"];
  if (bad.some((b) => desc.includes(b))) return false;
  return true;
}

async function downloadBuffer(url) {
  const res = await fetch(url, { signal: AbortSignal.timeout(15000) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const ab = await res.arrayBuffer();
  return Buffer.from(ab);
}

function updateManifest() {
  const present = entries.filter((e) => existsSync(`public${e.file}`));
  const ts = `// Generated by scripts/import-images.mjs. Do not edit by hand.
export interface SiteImage {
  src: string;
  alt: string;
}

/** Every imported image, keyed by its public path. */
export const IMAGES: Record<string, SiteImage> = {
${present.map((e) => `  ${JSON.stringify(e.file)}: { src: ${JSON.stringify(e.file)}, alt: ${JSON.stringify(e.alt)} },`).join("\n")}
};

/** Hero image for a page path, if one has been imported. */
export function heroImage(path: string): SiteImage | undefined {
  const file = "/images/pages/" + (path === "/" ? "home" : path.slice(1).replace(/\\//g, "--")) + ".webp";
  return IMAGES[file];
}
`;
  writeFileSync("src/content/images.ts", ts);
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

console.log(`\n======================================================`);
console.log(`Arranging images from #${START} to #${END}`);
console.log(`Images 1 to 86 are strictly preserved and NEVER modified.`);
console.log(`======================================================\n`);

let processed = 0;
let skipped = 0;
let errors = 0;

for (let n = START; n <= END; n++) {
  if (n < 87) continue; // SAFETY: never touch 1 to 86

  const entry = entries[n - 1];
  if (!entry) {
    console.warn(`[WARN] No entry for prompt #${n}`);
    continue;
  }

  const outWebp = `public${entry.file}`;
  if (existsSync(outWebp)) {
    console.log(`[${n}/${END}] already exists -> ${outWebp} (preserved)`);
    skipped++;
    continue;
  }

  const qScene = cleanScene(entry.scene);
  const qTopic = entry.path.split("/").pop().replace(/-/g, " ");
  const qParent = entry.path.split("/")[1] || "business";

  const queries = [
    qScene,
    `${qTopic} workplace`,
    `${qTopic} business`,
    `${qParent} professional work`,
  ];

  let candidatePhotos = [];
  for (const q of queries) {
    if (!q || q.length < 3) continue;
    const results = await searchUnsplash(q);
    const valid = results.filter(isPhotoGood);
    if (valid.length > 0) {
      candidatePhotos = valid;
      break;
    }
    await sleep(350);
  }

  let saved = false;
  for (const photo of candidatePhotos.slice(0, 4)) {
    try {
      const imgUrl = (photo.urls.raw || photo.urls.regular).split("?")[0] + "?w=1600&auto=format&fit=crop&q=82";
      const buf = await downloadBuffer(imgUrl);
      const meta = await sharp(buf).metadata();
      if (!meta.width || !meta.height || meta.width < 300) continue;

      const w = Math.min(1600, meta.width);
      const h = Math.round(w * 0.625);
      await sharp(buf)
        .resize(w, h, { fit: "cover", position: "attention" })
        .webp({ quality: 82 })
        .toFile(outWebp);

      // Save original
      writeFileSync(`${INCOMING}/done/${n}.jpg`, buf);
      usedPhotoIds.add(photo.id);

      saved = true;
      processed++;
      console.log(`[${n}/${END}] ✓ #${n} [${entry.path}] -> ${outWebp}`);
      break;
    } catch {
      continue;
    }
  }

  if (!saved) {
    console.warn(`[${n}/${END}] ✗ #${n} failed to find photo for: ${qScene}`);
    errors++;
  }

  if (processed % 10 === 0) {
    updateManifest();
  }

  await sleep(400);
}

updateManifest();
console.log(`\n======================================================`);
console.log(`Finished! Processed: ${processed}, Skipped: ${skipped}, Errors: ${errors}`);
console.log(`======================================================\n`);
