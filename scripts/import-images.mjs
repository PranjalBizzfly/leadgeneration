// Usage: node scripts/import-images.mjs
// 1. Converts every file in public/images/incoming/ named by its prompt number (e.g. "12.png",
//    numbering from docs/image-prompts.html) into a 1600×1000 WebP at that prompt's path.
// 2. Regenerates src/content/images.ts from all WebP files present, using each prompt's alt text.
// Converted originals are moved to public/images/incoming/done/ so a re-run never double-imports.
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const ORDER = ["home.json", "core-services.json", "strategies.json", "industries.json", "b2b-b2c.json", "capture-qualification.json", "tools-compare.json", "resources.json", "company-blog.json"];
const entries = ORDER.flatMap((f) => JSON.parse(readFileSync(`docs/image-prompts/${f}`, "utf8")));

const INCOMING = "public/images/incoming";
mkdirSync(`${INCOMING}/done`, { recursive: true });
mkdirSync("public/images/pages", { recursive: true });

const files = readdirSync(INCOMING).filter((f) => /^\d+\.(png|jpe?g|webp)$/i.test(f));
const problems = [];
for (const f of files.sort((a, b) => parseInt(a) - parseInt(b))) {
  const n = parseInt(f);
  const entry = entries[n - 1];
  if (!entry) {
    problems.push(`${f}: no prompt #${n}`);
    continue;
  }
  const out = `public${entry.file}`;
  const meta = await sharp(`${INCOMING}/${f}`).metadata();
  const w = Math.min(1600, meta.width ?? 1600);
  await sharp(`${INCOMING}/${f}`).resize(w, Math.round(w * 0.625), { fit: "cover", position: "attention" }).webp({ quality: 82 }).toFile(out);
  renameSync(`${INCOMING}/${f}`, `${INCOMING}/done/${f}`);
  console.log(`#${n} ${f} (${meta.width}×${meta.height}) → ${out}`);

}

// Manifest: keyed by the file path, plus a page-path lookup for hero images.
const present = entries.filter((e) => existsSync(`public${e.file}`));
const ts = `// Generated by scripts/import-images.mjs. Do not edit by hand.
import { RENAMED_ROUTES } from "@/lib/renamed-routes";

export interface SiteImage {
  src: string;
  alt: string;
}

/** Every imported image, keyed by its public path. */
export const IMAGES: Record<string, SiteImage> = {
${present.map((e) => `  ${JSON.stringify(e.file)}: { src: ${JSON.stringify(e.file)}, alt: ${JSON.stringify(e.alt)} },`).join("\n")}
};

/** Hero image for a page path, if one has been imported. */
export function heroImage(path: string): SiteImage | undefined {
  // Renamed pages keep the image file named after their original URL.
  const original = Object.keys(RENAMED_ROUTES).find((old) => RENAMED_ROUTES[old] === path) ?? path;
  const file = "/images/pages/" + (original === "/" ? "home" : original.slice(1).replace(/\\//g, "--")) + ".webp";
  return IMAGES[file];
}
`;
writeFileSync("src/content/images.ts", ts);
console.log(`\n${files.length} imported this run · ${present.length}/${entries.length} images now live`);
if (problems.length) console.log(problems.join("\n"));
