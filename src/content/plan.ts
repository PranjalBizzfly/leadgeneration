import type { GroupKey, PlanEntry } from "./types";

/**
 * The complete 300-page site plan. Every indexable route lives here.
 * phase 1 = implemented in Phase 1; phase 2 = reserved for Phase 2 (not yet rendered).
 */
type Row = [path: string, title: string, audience: string, outline: string, phase?: 1 | 2];

function group(key: GroupKey, rows: Row[], defaultPhase: 1 | 2): PlanEntry[] {
  return rows.map(([path, title, audience, outline, phase]) => ({
    path,
    title,
    group: key,
    audience,
    outline,
    phase: phase ?? defaultPhase,
  }));
}

